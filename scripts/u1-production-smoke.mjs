import {readFile,writeFile,mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.QA_BASE_URL||'http://localhost:3001';
const form=new FormData();form.append('files',new Blob([await readFile('public/reference-u1.pdf')],{type:'application/pdf'}),'Supplied Form U-1.pdf');
const uploaded=await fetch(`${base}/api/u1/upload`,{method:'POST',body:form});
assert.equal(uploaded.status,200);const {pages}=await uploaded.json();assert.equal(pages.length,3);
const created=await fetch(`${base}/api/u1/records`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'Supplied reference · Form U-1',pages})});
assert.equal(created.status,200);const {record}=await created.json();
const response=await fetch(`${base}/api/u1/process`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({id:record.id})});
const lines=(await response.text()).split('\n').filter(Boolean).map(s=>JSON.parse(s));
const final=lines.find(x=>x.stage==='complete');assert.ok(final,JSON.stringify(lines));
assert.equal(final.record.status,'Review Required');
assert.equal(final.record.fields.find(f=>f.id==='year').value,'2017');
assert.equal(final.record.fields.find(f=>f.id==='manufacturer').value,'');
assert.equal(final.record.fields.find(f=>f.id==='tube.1.number').value,'352');
const approval=await fetch(`${base}/api/u1/records/${record.id}`,{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({action:'approve'})});
assert.equal(approval.status,200);const approved=(await approval.json()).record;
assert.equal(approved.status,'Approved');assert.ok(approved.fields.every(f=>['Verified','Corrected','N/A'].includes(f.status)));
await mkdir('tmp/u1-tests',{recursive:true});
await writeFile('tmp/u1-tests/production-record.json',JSON.stringify(final.record,null,2));
console.log(JSON.stringify({recordId:record.id,status:approved.status,fields:approved.fields.length,productionUploadAndOCR:'passed',singleEngineeringConfirmation:'passed'}));
