import { test, expect } from '@playwright/test'

test('all seven role entries navigate to their workspace', async ({ page }) => {
  for (const [name, route] of [['Project Manager','command-center'],['Technical / Lab','technical'],['Operations','readiness'],['Commercial','cost-impact'],['Procurement / Logistics','readiness'],['Management','management'],['Admin','admin']]) {
    await page.goto('/')
    await page.getByRole('button', { name: new RegExp('^'+name.replaceAll('/', '\\/')) }).click()
    await page.getByRole('button', {name:'Enter Workspace'}).click()
    await expect(page).toHaveURL(new RegExp('/'+route+'$'))
  }
})
