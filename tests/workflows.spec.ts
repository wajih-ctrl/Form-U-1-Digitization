for(const kind of ['reject','clarify','escalate']) test(`${kind} dialog validates and persists`, async ({page}) => {
  await page.goto('/changes/cr-003')
  const trigger={reject:'Reject',clarify:'Request Clarification',escalate:'Escalate'}[kind]
  await page.getByRole('button',{name:trigger,exact:true}).click()
  const dialog=page.getByRole('dialog')
  const confirm=dialog.getByRole('button',{name:kind==='reject'?'Confirm Reject':kind==='clarify'?'Confirm':'Confirm Escalation',exact:true})
  await expect(confirm).toBeDisabled()
  await dialog.getByRole('textbox').fill('   ')
  await expect(confirm).toBeDisabled()
  await dialog.getByRole('textbox').fill('The team must verify the secondary train scope.')
  await confirm.click()
  await page.reload()
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('meridian-v2:changes')!).find((c:any)=>c.id==='cr-003'))
  expect(saved.status).toBe({reject:'rejected',clarify:'clarification-requested',escalate:'escalated'}[kind])
  if(kind==='escalate'){await page.goto('/management');await expect(page.getByText('CR-003 Escalated')).toBeVisible()}
})
