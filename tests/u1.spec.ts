test('camera capture, crop, rotate, retake and use-photo with simulated camera',async({browser})=>{
  const context=await browser.newContext({permissions:['camera']})
  const page=await context.newPage()
  await page.addInitScript(()=>{
    Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value:async()=>{
      const canvas=document.createElement('canvas');canvas.width=900;canvas.height=1200;const ctx=canvas.getContext('2d')!;ctx.fillStyle='#273b32';ctx.fillRect(0,0,900,1200);ctx.fillStyle='white';ctx.fillRect(80,80,740,1040);ctx.fillStyle='black';ctx.font='24px Arial';ctx.fillText('FORM U-1 · CAMERA QA',120,150)
      const stream=canvas.captureStream(10);setInterval(()=>ctx.fillRect(120,170,1,1),100);return stream
    }})
  })
  await page.goto('/');await page.getByRole('button',{name:'Capture a new form'}).click();await page.getByRole('button',{name:'Take Photos',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Take Photos'})).toBeVisible()
  await page.waitForFunction(()=>!!document.querySelector('video')?.videoWidth)
  await page.getByRole('button',{name:'Capture page',exact:true}).click()
  await page.getByRole('button',{name:'Rotate 90°',exact:true}).click()
  await page.getByRole('button',{name:'Rotate 90°',exact:true}).click()
  await page.getByRole('button',{name:'Rotate 90°',exact:true}).click()
  await page.getByRole('button',{name:'Rotate 90°',exact:true}).click()
  await page.getByRole('button',{name:'Detect edges',exact:true}).click()
  await page.getByRole('button',{name:'Use Photo',exact:true}).click()
  await expect(page.locator('.u-page-tile')).toHaveCount(1)
  await page.getByRole('button',{name:'Preview page 1',exact:true}).click();await page.getByRole('button',{name:'Retake',exact:true}).click()
  await page.waitForFunction(()=>!!document.querySelector('video')?.videoWidth)
  await page.getByRole('button',{name:'Capture page',exact:true}).click();await page.getByRole('button',{name:'Use Photo',exact:true}).click()
  await expect(page.locator('.u-page-tile')).toHaveCount(1)
  await expect(page.getByRole('button',{name:'Process Form',exact:true})).toBeDisabled()
  await context.close()
})
